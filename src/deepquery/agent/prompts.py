def format_history(turns: list[dict]) -> str:
    """之前几轮对话（旧的在前）拼成提示词里的一段；没有时返回空串。"""
    parts = []
    for i, t in enumerate(turns, 1):
        text = f"第 {i} 轮提问：{t['question']}"
        if t.get("sql"):
            text += f"\n执行的 SQL：\n```sql\n{t['sql']}\n```"
        if t.get("answer"):
            text += f"\n回答：{t['answer']}"
        parts.append(text)
    return "\n\n".join(parts)


